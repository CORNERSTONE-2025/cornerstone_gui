"""GUI settings: where the CORNERSTONE package, its virtualenv, the database and the workspace live.

Settings are read from (in order of precedence):
1. environment variables ``CS_GUI_*``;
2. ``gui_settings.json`` in the project root, or the file named by ``CS_GUI_SETTINGS_FILE``
   (not versioned, see ``config/gui_settings.example.json``);
3. defaults: the ``cornerstone`` package importable by this interpreter, otherwise a sibling
   checkout ``../cornerstone_db_package``; its ``.venv`` if present; the database named in
   ``cornerstone/configs/db_config.json``.

Two modes exist and are kept strictly separated:
- ``real``: the real SQLite database of the package, workspace ``workspace/``;
- ``demo``: a synthetic database generated by ``cs_gui.demo``, workspace ``workspace_demo/``.
  Everything produced in demo mode is tagged ``mode="demo"`` and shown with a banner.
"""
from __future__ import annotations

import importlib.util
import json
import os
import sys
from dataclasses import asdict, dataclass, field
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
SETTINGS_FILE = Path(os.environ.get("CS_GUI_SETTINGS_FILE") or PROJECT_ROOT / "gui_settings.json")


def _default_cornerstone_root() -> str:
    spec = importlib.util.find_spec("cornerstone")
    if spec and spec.origin:
        return str(Path(spec.origin).resolve().parent.parent)
    return str(PROJECT_ROOT.parent / "cornerstone_db_package")


DEFAULT_CORNERSTONE_ROOT = _default_cornerstone_root()


@dataclass
class Settings:
    cornerstone_root: str = DEFAULT_CORNERSTONE_ROOT
    cornerstone_python: str = ""          # default: <cornerstone_root>/.venv/bin/python, else this interpreter
    db_path: str = ""                      # default: local_db_path in db_config.json
    workspace: str = str(PROJECT_ROOT / "workspace")
    demo_workspace: str = str(PROJECT_ROOT / "workspace_demo")
    mode: str = "real"                     # "real" | "demo"
    min_free_disk_gb: float = 5.0
    extra: dict = field(default_factory=dict)

    # ------------------------------------------------------------------ derived values
    @property
    def python(self) -> str:
        if self.cornerstone_python:
            return self.cornerstone_python
        venv = Path(self.cornerstone_root) / ".venv" / "bin" / "python"
        return str(venv) if venv.exists() else sys.executable

    @property
    def active_workspace(self) -> Path:
        return Path(self.demo_workspace if self.mode == "demo" else self.workspace)

    @property
    def demo_db_path(self) -> Path:
        return Path(self.demo_workspace) / "demo_cornerstone.sqlite"

    @property
    def real_db_path(self) -> str:
        """The real database, whatever the mode (it is where the database download writes)."""
        return self.db_path or _db_path_from_cornerstone(self.cornerstone_root)

    @property
    def active_db_path(self) -> str:
        if self.mode == "demo":
            return str(self.demo_db_path)
        return self.real_db_path

    def problems(self) -> list[str]:
        """Human readable list of configuration problems (empty if everything is in place)."""
        out = []
        root = Path(self.cornerstone_root)
        if not (root / "cornerstone" / "__init__.py").exists():
            out.append(f"CORNERSTONE package not found in '{root}' (cornerstone/__init__.py is missing).")
        if not Path(self.python).exists():
            out.append(f"CORNERSTONE Python interpreter not found: '{self.python}'.")
        db = self.active_db_path
        if not db or not Path(db).exists():
            hint = (" Generate the demo DB from the Home page." if self.mode == "demo"
                    else " Download it from the Home page (Database section).")
            out.append(f"SQLite database not found: '{db}'.{hint}")
        return out


def _db_path_from_cornerstone(root: str) -> str:
    """``local_db_path`` of the package config; relative paths are relative to the package checkout."""
    cfg = Path(root) / "cornerstone" / "configs" / "db_config.json"
    try:
        path = json.loads(cfg.read_text())["local_db_path"]
    except (OSError, KeyError, json.JSONDecodeError):
        path = "db/cornerstone.sqlite"
    return str((Path(root) / Path(path).expanduser()).resolve())


PATH_KEYS = ("cornerstone_root", "cornerstone_python", "db_path", "workspace", "demo_workspace")

_ENV = {
    "CS_GUI_CORNERSTONE_ROOT": "cornerstone_root",
    "CS_GUI_CORNERSTONE_PYTHON": "cornerstone_python",
    "CS_GUI_DB_PATH": "db_path",
    "CS_GUI_WORKSPACE": "workspace",
    "CS_GUI_DEMO_WORKSPACE": "demo_workspace",
    "CS_GUI_MODE": "mode",
}


def load_settings(path: Path | None = None) -> Settings:
    path = path or SETTINGS_FILE
    data: dict = {}
    if path.exists():
        data = json.loads(path.read_text())
    for env, key in _ENV.items():
        if os.environ.get(env):
            data[key] = os.environ[env]
    known = {k: v for k, v in data.items() if k in Settings.__dataclass_fields__}
    # relative paths are relative to the project root: the runner works inside the workspace, so a
    # relative path would point somewhere else there
    for key in PATH_KEYS:
        if known.get(key) and not Path(known[key]).is_absolute():
            known[key] = str((PROJECT_ROOT / known[key]).resolve())
    s = Settings(**known)
    if s.mode not in ("real", "demo"):
        raise ValueError(f"Invalid mode: {s.mode!r} (expected 'real' or 'demo')")
    return s


def save_settings(s: Settings, path: Path | None = None) -> None:
    path = path or SETTINGS_FILE
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(asdict(s), indent=2))
    os.replace(tmp, path)
