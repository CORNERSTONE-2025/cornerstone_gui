"""GUI settings: where the CORNERSTONE package, its virtualenv, the database and the workspace live.

Settings are read from (in order of precedence):
1. environment variables ``CS_GUI_*``;
2. ``gui_settings.json`` in the project root (not versioned, see ``config/gui_settings.example.json``);
3. defaults derived from the CORNERSTONE checkout (``cornerstone/configs/db_config.json``).

Two modes exist and are kept strictly separated:
- ``real``: the real SQLite database of the package, workspace ``workspace/``;
- ``demo``: a synthetic database generated by ``cs_gui.demo``, workspace ``workspace_demo/``.
  Everything produced in demo mode is tagged ``mode="demo"`` and shown with a banner.
"""
from __future__ import annotations

import json
import os
from dataclasses import asdict, dataclass, field
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
SETTINGS_FILE = PROJECT_ROOT / "gui_settings.json"
DEFAULT_CORNERSTONE_ROOT = "/bigdisk/daniele/cornerstone_module"


@dataclass
class Settings:
    cornerstone_root: str = DEFAULT_CORNERSTONE_ROOT
    cornerstone_python: str = ""          # default: <cornerstone_root>/.venv/bin/python
    db_path: str = ""                      # default: local_db_path in db_config.json
    workspace: str = str(PROJECT_ROOT / "workspace")
    demo_workspace: str = str(PROJECT_ROOT / "workspace_demo")
    mode: str = "real"                     # "real" | "demo"
    min_free_disk_gb: float = 5.0
    extra: dict = field(default_factory=dict)

    # ------------------------------------------------------------------ derived values
    @property
    def python(self) -> str:
        return self.cornerstone_python or str(Path(self.cornerstone_root) / ".venv" / "bin" / "python")

    @property
    def active_workspace(self) -> Path:
        return Path(self.demo_workspace if self.mode == "demo" else self.workspace)

    @property
    def demo_db_path(self) -> Path:
        return Path(self.demo_workspace) / "demo_cornerstone.sqlite"

    @property
    def active_db_path(self) -> str:
        if self.mode == "demo":
            return str(self.demo_db_path)
        if self.db_path:
            return self.db_path
        return _db_path_from_cornerstone(self.cornerstone_root)

    def problems(self) -> list[str]:
        """Human readable list of configuration problems (empty if everything is in place)."""
        out = []
        root = Path(self.cornerstone_root)
        if not (root / "cornerstone" / "__init__.py").exists():
            out.append(f"Pacchetto CORNERSTONE non trovato in '{root}' (manca cornerstone/__init__.py).")
        if not Path(self.python).exists():
            out.append(f"Interprete Python di CORNERSTONE non trovato: '{self.python}'.")
        db = self.active_db_path
        if not db or not Path(db).exists():
            hint = " Genera il DB demo dalla Home." if self.mode == "demo" else ""
            out.append(f"Database SQLite non trovato: '{db}'.{hint}")
        return out


def _db_path_from_cornerstone(root: str) -> str:
    cfg = Path(root) / "cornerstone" / "configs" / "db_config.json"
    try:
        return json.loads(cfg.read_text())["local_db_path"]
    except (OSError, KeyError, json.JSONDecodeError):
        return str(Path(root) / "db" / "cornerstone.sqlite")


_ENV = {
    "CS_GUI_CORNERSTONE_ROOT": "cornerstone_root",
    "CS_GUI_CORNERSTONE_PYTHON": "cornerstone_python",
    "CS_GUI_DB_PATH": "db_path",
    "CS_GUI_WORKSPACE": "workspace",
    "CS_GUI_DEMO_WORKSPACE": "demo_workspace",
    "CS_GUI_MODE": "mode",
}


def load_settings(path: Path | None = None) -> Settings:
    path = path or SETTINGS_FILE
    data: dict = {}
    if path.exists():
        data = json.loads(path.read_text())
    for env, key in _ENV.items():
        if os.environ.get(env):
            data[key] = os.environ[env]
    known = {k: v for k, v in data.items() if k in Settings.__dataclass_fields__}
    s = Settings(**known)
    if s.mode not in ("real", "demo"):
        raise ValueError(f"Modalità non valida: {s.mode!r} (attese 'real' o 'demo')")
    return s


def save_settings(s: Settings, path: Path | None = None) -> None:
    path = path or SETTINGS_FILE
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(asdict(s), indent=2))
    os.replace(tmp, path)
